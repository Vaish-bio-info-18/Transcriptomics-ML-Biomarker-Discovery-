import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from google.colab import files

from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    confusion_matrix,
    classification_report,
    roc_curve,
    roc_auc_score
)
from sklearn.inspection import permutation_importance

uploaded = files.upload()

filename = list(uploaded.keys())[0]
dat = pd.read_csv(filename)

print("Dataset shape:", dat.shape)
print(dat.head())
print("\nColumn names:")
print(dat.columns.tolist())

genes = [
    "AC092821",
    "IGHA2",
    "IGHV2",
    "SLC27A3",
    "HLAB",
    "IGHV5",
    "TRBJ1",
    "IGHV4",
    "SPC25",
    "IGHV3"
]

missing = [g for g in genes if g not in dat.columns]

if missing:
    print("Missing columns:", missing)
else:
    print("All 10 gene columns found successfully.")

possible_labels = ["class", "Class", "group", "Group", "condition", "Condition"]

label_col = next((c for c in possible_labels if c in dat.columns), None)

print("Detected outcome column:", label_col)

print(dat[label_col].value_counts())

dat["PTSD"] = (
    dat[label_col]
    .astype(str)
    .str.strip()
    .str.lower()
    .map({
        "patient": 1,
        "ptsd": 1,
        "control": 0,
        "healthy": 0
    })
)

print(dat["PTSD"].value_counts())

print(dat[dat["PTSD"].isna()][label_col])

X = dat[genes].copy()
y = dat["PTSD"].copy()

X = X.apply(pd.to_numeric, errors="coerce")

print("X shape:", X.shape)
print("y shape:", y.shape)
print("\nMissing values:")
print(X.isna().sum())

X = X.fillna(X.median())

ann = Pipeline([
    ("scaler", StandardScaler()),
    ("mlp", MLPClassifier(
        hidden_layer_sizes=(5,),
        activation="logistic",
        solver="lbfgs",
        alpha=0.01,
        max_iter=5000,
        random_state=42
    ))
])

cv = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

y_prob = cross_val_predict(
    ann,
    X,
    y,
    cv=cv,
    method="predict_proba"
)[:, 1]

y_pred = (y_prob >= 0.5).astype(int)

accuracy = accuracy_score(y, y_pred)
balanced_accuracy = balanced_accuracy_score(y, y_pred)
auc = roc_auc_score(y, y_prob)

print("ANN Performance")
print("----------------------")
print(f"Accuracy:          {accuracy:.3f}")
print(f"Balanced Accuracy: {balanced_accuracy:.3f}")
print(f"ROC-AUC:           {auc:.3f}")

print("\nClassification Report:")
print(
    classification_report(
        y,
        y_pred,
        target_names=["Control", "Patient"]
    )
)

cm = confusion_matrix(y, y_pred)

plt.figure(figsize=(6, 5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="RdPu",
    xticklabels=["Control", "Patient"],
    yticklabels=["Control", "Patient"]
)

plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("ANN Confusion Matrix")
plt.show()

fpr, tpr, thresholds = roc_curve(y, y_prob)

plt.figure(figsize=(7, 6))

plt.plot(
    fpr,
    tpr,
    linewidth=2,
    label=f"ANN (AUC = {auc:.3f})"
)

plt.plot(
    [0, 1],
    [0, 1],
    linestyle="--"
)

plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.title("ROC Curve for ANN-based PTSD Classification")

plt.legend()
plt.grid(alpha=0.3)

plt.show()

ann.fit(X, y)

ann_sgd = Pipeline([
    ("scaler", StandardScaler()),
    ("mlp", MLPClassifier(
        hidden_layer_sizes=(5,),
        activation="logistic",
        solver="adam",
        learning_rate_init=0.001,
        alpha=0.01,
        max_iter=3000,
        random_state=42
    ))
])

ann_sgd.fit(X, y)

mlp = ann_sgd.named_steps["mlp"]

plt.figure(figsize=(7, 5))
plt.plot(mlp.loss_curve_)
plt.xlabel("Iteration")
plt.ylabel("Loss")
plt.title("ANN Training Loss")
plt.grid(alpha=0.3)
plt.show()

result = permutation_importance(
    ann,
    X,
    y,
    n_repeats=100,
    random_state=42,
    scoring="roc_auc"
)

importance = pd.DataFrame({
    "Gene": genes,
    "Importance": result.importances_mean,
    "SD": result.importances_std
})

importance = importance.sort_values(
    "Importance",
    ascending=False
)

print(importance)

plt.figure(figsize=(9, 6))

plt.barh(
    importance["Gene"],
    importance["Importance"],
)

plt.xlabel("Permutation Importance")
plt.ylabel("Gene")
plt.title("ANN Feature Importance for PTSD Classification")

plt.gca().invert_yaxis()

plt.tight_layout()
plt.show()

importance.to_csv(
    "ANN_gene_importance.csv",
    index=False
)

predictions = pd.DataFrame({
    "Actual": y,
    "Predicted": y_pred,
    "PTSD_Probability": y_prob
})

predictions.to_csv(
    "ANN_predictions.csv",
    index=False
)

print("Results saved successfully.")

files.download("ANN_gene_importance.csv")
files.download("ANN_predictions.csv")