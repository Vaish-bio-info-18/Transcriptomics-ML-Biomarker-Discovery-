display(dat.head())

genes = [
    "AC092821",
    "IGHA2",
    "IGHV2",
    "SLC27A3",
    "HLAB",
    "IGHV5",
    "TRBJ1",
    "IGHV4",
    "SPC25",
    "IGHV3"
]

missing = [g for g in genes if g not in dat.columns]

if len(missing) == 0:
    print("✅ All 10 genes found!")
else:
    print("❌ Missing genes:", missing)

dat = dat.rename(columns={"AC092821.1": "AC092821"})

label_col = "class"

print(dat[label_col].value_counts())

dat["PTSD"] = (
    dat["class"]
    .astype(str)
    .str.strip()
    .str.lower()
    .map({
        "patient": 1,
        "ptsd": 1,
        "control": 0,
        "healthy": 0
    })
)

print(dat["PTSD"].value_counts())

dat["class"].unique()

X = dat[genes].copy()

X = X.apply(pd.to_numeric, errors="coerce")

y = dat["PTSD"].astype(int)

print("X:", X.shape)
print("y:", y.shape)

print("\nMissing values:")
print(X.isna().sum())



X = X.fillna(X.median())

cv = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

models = {

    "Logistic Regression": Pipeline([
        ("scaler", StandardScaler()),
        ("model", LogisticRegression(
            max_iter=5000,
            C=0.1
        ))
    ]),

    "Random Forest": RandomForestClassifier(
        n_estimators=500,
        max_depth=3,
        min_samples_leaf=2,
        random_state=42
    ),

    "SVM": Pipeline([
        ("scaler", StandardScaler()),
        ("model", SVC(
            kernel="rbf",
            C=1,
            probability=True,
            random_state=42
        ))
    ]),

    "KNN": Pipeline([
        ("scaler", StandardScaler()),
        ("model", KNeighborsClassifier(
            n_neighbors=3
        ))
    ]),

    "Decision Tree": DecisionTreeClassifier(
        max_depth=3,
        min_samples_leaf=2,
        random_state=42
    ),

    "Naive Bayes": Pipeline([
        ("scaler", StandardScaler()),
        ("model", GaussianNB())
    ]),

    "Gradient Boosting": GradientBoostingClassifier(
        n_estimators=100,
        max_depth=2,
        learning_rate=0.05,
        random_state=42
    ),

    "ANN": Pipeline([
        ("scaler", StandardScaler()),
        ("model", MLPClassifier(
            hidden_layer_sizes=(5,),
            activation="logistic",
            solver="lbfgs",
            alpha=0.01,
            max_iter=5000,
            random_state=42
        ))
    ])
}

results = []
predictions = {}

for name, model in models.items():

    prob = cross_val_predict(
        model,
        X,
        y,
        cv=cv,
        method="predict_proba"
    )[:, 1]

    pred = (prob >= 0.5).astype(int)

    predictions[name] = {
        "prob": prob,
        "pred": pred
    }

    results.append({
        "Model": name,
        "Accuracy": accuracy_score(y, pred),
        "Balanced Accuracy": balanced_accuracy_score(y, pred),
        "Precision": precision_score(y, pred, zero_division=0),
        "Recall": recall_score(y, pred, zero_division=0),
        "F1": f1_score(y, pred, zero_division=0),
        "ROC-AUC": roc_auc_score(y, prob)
    })

results_df = pd.DataFrame(results)

results_df = results_df.sort_values(
    "ROC-AUC",
    ascending=False
)

display(results_df)

plt.figure(figsize=(9, 7))

